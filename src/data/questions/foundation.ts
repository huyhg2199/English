/** 46 câu Sân ga (hàng A 12 câu, C 14 câu: F15 5, F16 4, story 43, 44; B, D 10 câu), theo thứ tự hàng A → D. */
export const FOUNDATION_QUESTIONS: readonly ChoiceQuestion[] = [...ROW_A, ...ROW_B, ...ROW_C, ...ROW_D]

/** Id bài kiểm tra của từng hàng. */
export const ROW_QUIZ_ID: Readonly<Record<RowId, string>> = {
  A: 'quiz-f-a',
  B: 'quiz-f-b',
  C: 'quiz-f-c',
  D: 'quiz-f-d',
}

/** Số câu mỗi lần kiểm tra hàng. */
export const ROW_QUIZ_SIZE = 8

/** Mỗi viên ít nhất mấy câu (hàng A, B 6 viên; C 4 viên; D 2 viên → luôn đủ 8). */
const MIN_PER_LESSON: Readonly<Record<RowId, number>> = { A: 1, B: 1, C: 2, D: 4 }

function rowQuiz(row: RowId): QuizDef {
  const bricks = bricksOfRow(row)
  const lessonIds = bricks.map((b) => brickLessonId(b.id))
  return {
    id: ROW_QUIZ_ID[row],
    title: `Kiểm tra hàng ${row} · ${ROW_TITLES[row]}`,
    description: `${ROW_QUIZ_SIZE} câu về ${bricks[0].id}–${bricks.at(-1)!.id}. Đúng từ 6/8 (70%) là hàng ${row} tính là xong.`,
    lessonIds,
    size: ROW_QUIZ_SIZE,
    minPerLesson: MIN_PER_LESSON[row],
    homeLessonId: lessonIds[0],
  }
}

/** 4 bài kiểm tra hàng (`quiz-f-a` … `quiz-f-d`), không nằm trong `QUIZZES`. */
export const FOUNDATION_QUIZZES: readonly QuizDef[] = ROW_IDS.map(rowQuiz)

/** Bài kiểm tra của hàng `row`. */
export function foundationQuiz(row: RowId): QuizDef {
  return FOUNDATION_QUIZZES[ROW_IDS.indexOf(row)]
}
